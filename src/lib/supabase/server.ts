import "server-only";
import { createServerClient } from "@supabase/ssr";
import { cookies } from "next/headers";
import { env } from "@/lib/env";

export async function createClient() {
  if (!env.supabaseUrl || !env.supabasePublishableKey) return null;
  const store = await cookies();
  return createServerClient(env.supabaseUrl, env.supabasePublishableKey, {
    cookies: {
      getAll: () => store.getAll(),
      setAll: (list) => {
        try { list.forEach(({ name, value, options }) => store.set(name, value, options)); } catch { /* Server Component: ignorado, proxy renova */ }
      },
    },
  });
}
export type ServerClient = NonNullable<Awaited<ReturnType<typeof createClient>>>;
